"""Install the umcares panvim boards: `umcares panels install [--commit]`.

The home board (`umcares`, hand written, local only, refreshes every 60 s) keeps everything it had and gains navigation keys. Six more boards read
the web app through `umcares panel <view>` (see panel.py): projects, jobs, project, recipes, plan, exports. They refresh only while their popup is
open, show counts and names but never captions, and every key on them is read-only: lowercase keys look, and Enter on a row only remembers a choice
in the panel's state file. Nothing here binds a key that renders, cancels or deletes (that is a later phase, and it will ask for `yes` first).

Safe to re-run: without `--commit` it only says what it would do; with it, any keys or syntax file that would change is copied to `<name>.bak-<time>`
first, and `panvim audit` runs at the end. A board that already exists is not created again.
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
import time
from pathlib import Path

ROW = "^  (%S+)"
START = "# >>> umcares panels (managed by `umcares panels install`; edits between the markers are replaced)"
END = "# <<< umcares panels"

# name -> (view, title, refresh seconds, size). The plan board asks the web app to build a plan on each refresh, so it is slower.
BOARDS = {
    "umcares-projects": ("projects", "umcares-projects", 15, "80%x60%"),
    "umcares-jobs": ("jobs", "umcares-jobs", 10, "80%x60%"),
    "umcares-project": ("project", "umcares-project", 30, "70%x50%"),
    "umcares-recipes": ("recipes", "umcares-recipes", 30, "70%x50%"),
    "umcares-plan": ("plan", "umcares-plan", 60, "80%x70%"),
    "umcares-exports": ("exports", "umcares-exports", 30, "80%x60%"),
}

# Navigation, the same on every board: key, label, board.
NAV = (
    ("j", "jobs: what is rendering and what is waiting", "umcares-jobs"),
    ("p", "projects: counts per project", "umcares-projects"),
    ("o", "this project: files, recipes, videos", "umcares-project"),
    ("m", "recipes saved in this project", "umcares-recipes"),
    ("t", "timeline of the chosen recipe (plan, nothing renders)", "umcares-plan"),
    ("f", "finished videos, newest first", "umcares-exports"),
)

SYNTAX = """# umcares boards colouring. Roles from ~/.config/panvim/theme.conf.
# No "/" in any regex: the engine uses it as the :syntax delimiter.
head\tsection,bold\t^\\S.*:$
ok\tok,bold\t^  ✓\\|✓\\|\\<done\\>
bad\tbad,bold\t✗\\|\\<failed\\>\\|not reachable\\|no project chosen\\|no recipe chosen
warn\twarn\t^warning:\\|^    !\\|^        !
busy\tsection\t\\<running\\>\\|\\<queued\\>
bar\tok\t█\\+
dim\tdim\t░\\+\\|(current)\\|(could not read)
size\tdim\t[0-9]\\+ s\\>\\|[0-9]\\+s\\>
"""


class PanelsError(Exception):
    """Something to fix before installing, in words."""


def _cfg() -> Path:
    return Path.home() / ".config" / "panvim"


def _bin() -> Path:
    return Path.home() / ".local" / "bin"


def nav_lines(skip: str | None = None) -> list[str]:
    return [f"{k}\t{label}\tpopup\t{board}" for k, label, board in NAV if board != skip]


def choose_then_open(set_args: str, board: str) -> str:
    """Remember the choice, then open the next board without waiting for it: `term` closes when its command exits, and a command that waited for the popup
    would leave this pane open underneath it. If the choice is refused its message stays on screen until a key."""
    return (f"if umcares panel set {set_args} >/dev/null; then nohup panvim popup {board} >/dev/null 2>&1 & "
            "else read -r -n1 -p 'could not choose that; press a key: '; fi")


def board_keys(name: str) -> str:
    """The whole keys file of one network board. Lowercase and Enter only; nothing renders, deletes or cancels."""
    out = ["# GENERATED by `umcares panels install`: do not hand-edit, re-run it instead.",
           "# Every key here only looks. Enter on a row remembers the choice (a small state file) and opens the next board.",
           "[global]",
           "h\thome: the local board\tpopup\tumcares", *nav_lines(skip=name), "q\tquit\tquit\t"]
    view = BOARDS[name][0]
    if view == "projects":
        out += ["[direct]", f"<CR>\tEnter: choose this project, open its board\tterm\t{choose_then_open('{row}', 'umcares-project')}"]
    elif view == "jobs":
        out += ["[direct]", f"<CR>\tEnter: choose the project of this job, open its board\tterm\t{choose_then_open('{row}', 'umcares-project')}"]
    elif view == "recipes":
        out += ["[direct]", f"<CR>\tEnter: choose this recipe, open its timeline\tterm\t{choose_then_open('--recipe {row}', 'umcares-plan')}"]
    return "\n".join(out) + "\n"


def home_block() -> str:
    return "\n".join([START, "# these open the boards that read the web app; the home board itself stays local only", *nav_lines(), END]) + "\n"


def merge_home(text: str) -> str:
    """The home keys file with the managed block (re)placed just before its quit key; every other line is left as it was."""
    text = re.sub(re.escape(START) + r".*?" + re.escape(END) + r"\n?", "", text, flags=re.S)
    lines = text.splitlines(keepends=True)
    for i, line in enumerate(lines):
        if line.split("\t")[0] == "q" and line.rstrip("\n").split("\t")[2:3] == ["quit"]:
            lines[i:i] = [home_block()]
            return "".join(lines)
    return text.rstrip("\n") + "\n" + home_block()


HOME_NOTE = """# The boards below read the web app (never ssh, billing or credentials) and refresh only while their popup is open; keys on this board that
# open them are in keys.tsv (j p o m t f). This board itself must stay LOCAL ONLY, because it re-renders every 60 s while open.
"""


def _backup(path: Path, new: str, stamp: str) -> str | None:
    if path.exists() and path.read_text(encoding="utf-8") != new:
        dest = path.with_name(f"{path.name}.bak-{stamp}")
        shutil.copy2(path, dest)
        return str(dest)
    return None


def _run(cmd: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True, timeout=120)


def _existing() -> set[str]:
    p = _run(["panvim", "popups", "--all", "--json"])
    try:
        return {r["name"] for r in json.loads(p.stdout or "[]")}
    except (ValueError, KeyError, TypeError):
        raise PanelsError("panvim popups --all --json did not answer with a list; is panvim up to date?") from None


def install(commit: bool, url: str = "") -> dict:
    """The plan (no commit), or do it. Raises PanelsError when panvim or umcares is not on PATH."""
    if not shutil.which("panvim"):
        raise PanelsError("panvim is not on PATH")
    if not shutil.which("umcares"):
        raise PanelsError("umcares is not on PATH (the boards run `umcares panel ...`); install it first")
    cfg = _cfg()
    have = _existing()
    home_keys = cfg / "umcares" / "keys.tsv"
    plan = {"committed": commit, "boards": [{"panel": n, "view": v[0], "exists": n in have, "keys_file": str(cfg / n / "keys.tsv")} for n, v in BOARDS.items()],
            "home": {"keys_file": str(home_keys), "exists": home_keys.exists(), "adds": [k for k, _l, _b in NAV]},
            "bakes_web_url": bool(url)}
    if not commit:
        plan["next"] = "run again with --commit; changed keys files are backed up first and `panvim audit` runs after"
        return plan
    stamp = time.strftime("%Y%m%d%H%M%S")
    backups, created, failures = [], [], []
    prefix = f"UMC_WEB_URL={json_quote(url)} " if url else ""
    for name, (view, title, interval, size) in BOARDS.items():
        if name not in have:
            cmd = ["panvim", "new", name, "--render", f'{prefix}umcares panel {view} > "$PANVIM_OUT"', "--title", title, "--interval", str(interval),
                   "--row", ROW, "--size", size, "--hidden", "--commit"]
            p = _run(cmd)
            if p.returncode not in (0, 1):                      # `panvim new` runs the audit after; 1 means findings
                failures.append({"panel": name, "error": (p.stderr or p.stdout)[-300:]})
                continue
            created.append(name)
        (cfg / name).mkdir(parents=True, exist_ok=True)
        for fname, new in (("keys.tsv", board_keys(name)), ("syntax.tsv", SYNTAX)):
            if name not in created:                              # `panvim new` just wrote a starter file; only a file that was already here is worth keeping
                b = _backup(cfg / name / fname, new, stamp)
                backups += [b] if b else []
            (cfg / name / fname).write_text(new, encoding="utf-8")
    if home_keys.exists():
        new = merge_home(home_keys.read_text(encoding="utf-8"))
        b = _backup(home_keys, new, stamp)
        backups += [b] if b else []
        home_keys.write_text(new, encoding="utf-8")
    else:
        failures.append({"panel": "umcares", "error": f"{home_keys} is missing; the home board was not changed"})
    _fix_home_popup_note()
    audit = _run(["panvim", "audit"])
    return {**plan, "created": created, "backups": backups, "failures": failures, "panvim_audit": {"exit": audit.returncode, "output": (audit.stdout + audit.stderr)[-1500:]}}


def json_quote(s: str) -> str:
    import shlex
    return shlex.quote(s)


def _fix_home_popup_note() -> None:
    """Add one comment to the home wrapper saying where the network boards live. Only that comment is added, and only once."""
    w = _bin() / "umcares-popup"
    if not w.exists():
        return
    text = w.read_text(encoding="utf-8")
    if "boards below read the web app" in text:
        return
    lines = text.splitlines(keepends=True)
    at = next((i for i, l in enumerate(lines) if l.startswith("CFG=")), None)
    if at is not None:
        lines[at:at] = [HOME_NOTE, "\n"]
        w.write_text("".join(lines), encoding="utf-8")
